import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DEFAULT_DRAFT } from '../src/domain/companion/draft.ts';
import { SOUL_IDENTITIES } from '../src/domain/companion/model.ts';
const { chromium } = await import(process.env.REALNPC_PLAYWRIGHT_MODULE ?? 'playwright');
const base = process.env.REALNPC_BASE_URL ?? 'http://127.0.0.1:3000';
assert.ok(['localhost', '127.0.0.1', '[::1]'].includes(new URL(base).hostname));
const browser = await chromium.launch({ channel: process.env.REALNPC_BROWSER_CHANNEL || undefined });
const artifacts = await mkdtemp(join(tmpdir(), 'realnpc-chat-qa-'));
const errors = [];
try {
  for (const width of [1440, 901, 801, 800, 641, 640, 390, 320]) {
    const height = width === 320 ? 568 : 900;
    const context = await browser.newContext({ viewport: { width, height }, reducedMotion: width === 1440 ? 'no-preference' : 'reduce', deviceScaleFactor: width === 390 ? 3 : 1 });
    const draft = structuredClone(DEFAULT_DRAFT);
    draft.step = draft.unlockedStep = 4;
    draft.config = { ...draft.config, ...SOUL_IDENTITIES.scout, soulId: 'scout', personality: { strangers: 'direct', friends: 'warm', partner: 'playful' } };
    draft.config.capabilities.mind.empathy = 91;
    draft.config.capabilities.expression.replyLength = 'brief';
    draft.config.capabilities.expression.language = 'zh';
    await context.addInitScript(draft => sessionStorage.setItem('realnpc:companion-demo:v1', JSON.stringify(draft)), draft);
    const page = await context.newPage();
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error' && !/Failed to load resource|net::ERR_FAILED/.test(m.text())) errors.push(m.text()); });
    let mode = 'success'; let held; const calls = [];
    let emotionalState = { relationship: 'strangers', mood: 'curious' };
    await page.route('**/chat', async route => {
      calls.push(route.request().postDataJSON());
      if (mode === 'hold') { held = route; return; }
      await route.fulfill({ status: mode === 'fail' ? 502 : 200, contentType: 'application/json', body: JSON.stringify(mode === 'fail' ? { error: 'Provider unavailable' } : { reply: 'Hello. Tell me about your day. <script>never execute</script>', ...emotionalState }) });
    });
    await page.goto(`${base}/demo/`);
    await page.getByRole('heading', { name: 'Mia', exact: true }).waitFor();
    await page.evaluate(() => document.fonts.ready);
    const composer = page.getByRole('textbox', { name: 'Message your Soul' });
    assert.ok(await composer.isEnabled(), 'Build with NEXT_PUBLIC_SOUL_API_URL to exercise chat');
    assert.equal(calls.length, 0);
    assert.equal(await page.getByRole('status', { name: 'Relationship stage' }).textContent(), 'Strangers');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    const heading = await page.locator('h1').boundingBox();
    assert.ok(heading.height < 60, 'Character heading stays on one line');
    const profile = page.getByRole('complementary', { name: 'Character settings' });
    const toggle = page.getByRole('button', { name: 'Character and settings', exact: true });
    assert.equal(await page.locator('.chat-header-avatar img').evaluate(img => img.complete && img.naturalWidth > 0), true);
    if (width <= 800) {
      assert.equal(await profile.isVisible(), false);
      await toggle.focus(); await page.keyboard.press('Enter');
      await profile.waitFor({ state: 'visible' });
    }
    await profile.getByText('25 · Female', { exact: true }).waitFor();
    assert.equal(await profile.getByText('Conversation settings', { exact: true }).count(), 0);
    const hearts = page.locator('.chat-hearts');
    assert.equal(await hearts.getAttribute('aria-label'), 'Closeness: 0 of 3 hearts');
    assert.equal(await composer.evaluate(el => getComputedStyle(el).resize), 'none');
    assert.equal(await profile.locator('[data-current="true"] dd').textContent(), 'Honest & direct');
    await page.screenshot({ path: join(artifacts, `${width}-profile.png`), fullPage: true });
    const openComposer = await composer.boundingBox();
    assert.ok(openComposer.y + openComposer.height < height, 'Opening settings preserves the composer');
    if (width <= 800) {
      await page.keyboard.press('Tab');
      assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Character settings');
      await page.keyboard.press('Escape');
      assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
      assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Character and settings');
      await page.keyboard.press('Space'); await profile.waitFor({ state: 'visible' });
      await page.keyboard.press('Space'); await profile.waitFor({ state: 'hidden' });
      await page.keyboard.press('Tab');
      assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Conversation', 'Hidden profile has no focus stops');
      await toggle.focus();
      await page.setViewportSize({ width: 1000, height });
      await profile.waitFor({ state: 'visible' });
      await page.waitForFunction(() => document.activeElement?.id === 'chat-profile');
      await page.setViewportSize({ width, height });
      await profile.waitFor({ state: 'hidden' });
      await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Character and settings');
    }
    await page.screenshot({ path: join(artifacts, `${width}-empty.png`), fullPage: true });
    await composer.focus();
    const box = await composer.boundingBox();
    assert.ok(box.y >= 0 && box.y + box.height < height, 'Composer is visible without scrolling');
    await composer.fill('你好');
    await composer.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true });
    assert.equal(await composer.inputValue(), '你好', 'IME confirmation does not send a message');
    assert.equal(calls.length, 0);
    await page.keyboard.press('Shift+Enter');
    assert.equal(await composer.inputValue(), '你好\n');
    await composer.fill('I enjoy small adventures.');
    mode = 'hold'; await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Stop reply' }).waitFor();
    assert.equal(await composer.inputValue(), '', 'Send clears the composer before a reply arrives');
    await composer.fill('Draft while waiting.');
    await page.keyboard.press('Enter');
    assert.equal(calls.length, 1, 'A pending response prevents another request without erasing the draft');
    await held.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: 'Provider unavailable' }) });
    await page.locator('.soul-chat-error').getByRole('alert').waitFor();
    await page.screenshot({ path: join(artifacts, `${width}-failed.png`), fullPage: true });
    assert.equal(await composer.inputValue(), 'Draft while waiting.');
    assert.equal(await page.locator('.soul-message-user').count(), 1);
    assert.equal(calls[0].config.capabilities.mind.empathy, 91);
    assert.equal(calls[0].config.capabilities.expression.replyLength, 'brief');
    assert.equal(calls[0].config.personality.strangers, 'direct');
    assert.equal(calls[0].relationship, 'strangers');
    assert.equal(await hearts.getAttribute('aria-label'), 'Closeness: 0 of 3 hearts');
    mode = 'success'; await page.getByRole('button', { name: 'Retry message' }).click();
    await page.locator('.soul-message-assistant').waitFor();
    assert.equal(await composer.inputValue(), 'Draft while waiting.', 'Retry completion preserves the newer draft');
    assert.equal(await page.locator('.soul-message-user').count(), 1, 'Retry preserves a single user bubble');
    assert.equal(await hearts.getAttribute('aria-label'), 'Closeness: 1 of 3 hearts');
    assert.equal(await page.getByRole('status', { name: 'NPC mood' }).textContent(), 'Curious');
    assert.equal(await page.locator('.soul-chat-log script').count(), 0);
    assert.deepEqual(calls[1].messages, calls[0].messages, 'Retry does not duplicate the user turn');
    mode = 'hold'; await composer.fill('One more thought.'); await page.getByRole('button', { name: 'Send message' }).press('Enter');
    await page.getByRole('button', { name: 'Stop reply' }).waitFor();
    assert.equal(await page.evaluate(() => document.activeElement?.id), 'soul-message', 'Sending from the button keeps focus where Escape stops the reply');
    assert.equal(await composer.inputValue(), '');
    await composer.fill('A separate draft.');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Stop reply');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(() => document.activeElement?.id), 'soul-message');
    await page.keyboard.press('Escape');
    assert.equal(await composer.inputValue(), 'A separate draft.');
    assert.equal(await page.getByRole('button', { name: 'Send message', exact: true }).isEnabled(), false);
    await page.getByRole('button', { name: 'Send message' }).waitFor();
    await held.abort().catch(() => {});
    assert.equal(await hearts.getAttribute('aria-label'), 'Closeness: 1 of 3 hearts');
    emotionalState = { relationship: 'friends', mood: 'calm' };
    mode = 'success'; await page.getByRole('button', { name: 'Retry message' }).click();
    await page.waitForFunction(() => document.querySelectorAll('.soul-message-assistant').length === 2);
    assert.equal(await page.getByRole('status', { name: 'Relationship stage' }).textContent(), 'Strangers');
    if (width > 800) assert.equal(await profile.locator('[data-current="true"] dd').textContent(), 'Honest & direct');
    assert.equal(await hearts.getAttribute('aria-label'), 'Closeness: 1 of 3 hearts', 'Retry completes only the second turn');
    assert.equal(await composer.inputValue(), 'A separate draft.');
    assert.equal(calls.at(-1).messages.at(-1).content, 'One more thought.');
    assert.equal(await page.getByRole('status', { name: 'NPC mood' }).textContent(), 'At ease');
    await page.screenshot({ path: join(artifacts, `${width}-conversation.png`), fullPage: true });
    emotionalState = { relationship: 'partner', mood: 'happy' };
    mode = 'hold'; await composer.fill('I welcome a closer connection.'); await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Stop reply' }).waitFor();
    await composer.fill('Keep this next draft.');
    await page.screenshot({ path: join(artifacts, `${width}-pending.png`), fullPage: true });
    await held.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ reply: 'I appreciate our conversations.', ...emotionalState }) });
    await page.waitForFunction(() => document.querySelector('.chat-hearts')?.getAttribute('aria-label') === 'Closeness: 2 of 3 hearts');
    assert.equal(await composer.inputValue(), 'Keep this next draft.', 'An ordinary successful reply preserves the next draft');
    assert.equal(await page.getByRole('status', { name: 'NPC mood' }).textContent(), 'Happy');
    mode = 'fail'; await composer.fill('Remove this failed message.'); await page.keyboard.press('Enter');
    await page.locator('.soul-chat-error').getByRole('alert').waitFor();
    await composer.fill('Keep this after removal.');
    await page.getByRole('button', { name: 'Remove message' }).click();
    assert.equal(await composer.inputValue(), 'Keep this after removal.');
    assert.equal(await page.getByRole('button', { name: 'Send message', exact: true }).isEnabled(), true);
    assert.equal(await page.locator('.soul-message-user').count(), 3);
    mode = 'success';
    emotionalState = { relationship: 'partner', mood: 'concerned' };
    await composer.fill('Today was difficult.'); await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('[aria-label="NPC mood"]')?.textContent === 'Concerned');
    assert.ok(calls.at(-1).messages.every(message => message.content !== 'Remove this failed message.'), 'Removed messages are excluded from subsequent history');
    assert.equal(await hearts.getAttribute('aria-label'), 'Closeness: 2 of 3 hearts', 'Fourth completed turn remains at two hearts');
    emotionalState = { relationship: 'friends', mood: 'reserved' };
    await composer.fill('I would like more space.'); await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('.chat-hearts')?.getAttribute('aria-label') === 'Closeness: 3 of 3 hearts');
    assert.equal(await page.locator('.soul-message-assistant').count(), 5, 'Five successful exchanges reach full hearts despite failures and cancellation');
    assert.equal(await page.getByRole('status', { name: 'NPC mood' }).textContent(), 'Reserved');
    assert.equal(calls.at(-1).completedTurns, 4);
    await page.screenshot({ path: join(artifacts, `${width}-full-hearts.png`), fullPage: true });
    await page.getByRole('button', { name: 'New conversation' }).focus();
    await page.keyboard.press('Space');
    await page.waitForFunction(() => document.querySelectorAll('.soul-message').length === 0);
    assert.equal(await page.getByRole('status', { name: 'Relationship stage' }).textContent(), 'Strangers');
    assert.equal(await hearts.getAttribute('aria-label'), 'Closeness: 0 of 3 hearts');
    assert.equal(await page.getByRole('status', { name: 'NPC mood' }).textContent(), 'Ready to chat');
    mode = 'hold'; await composer.fill('Cancel when I leave.'); await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Stop reply' }).waitFor();
    await page.getByRole('link', { name: 'Back to your Soul' }).click();
    await page.getByRole('heading', { name: 'Meet Mia', exact: true }).waitFor();
    await held.abort().catch(() => {});
    await page.getByRole('navigation', { name: 'Experience steps' }).getByRole('button', { name: 'Character', exact: true }).click();
    await page.locator('label').filter({ has: page.getByRole('radio', { name: 'Raymond', exact: true }) }).click();
    await page.getByRole('navigation', { name: 'Experience steps' }).getByRole('button', { name: 'Review', exact: true }).click();
    await page.getByRole('link', { name: 'Start Conversation with Raymond' }).click();
    await page.getByRole('heading', { name: 'Raymond', exact: true }).waitFor();
    assert.equal(await composer.evaluate(el => getComputedStyle(el).resize), 'none', 'Configurator CSS cannot restore the resize handle');
    assert.equal(await composer.evaluate(el => getComputedStyle(el).height), '72px');
    assert.equal(await hearts.getAttribute('aria-label'), 'Closeness: 0 of 3 hearts');
    assert.equal(await page.locator('.soul-message').count(), 0);
    assert.equal(await composer.inputValue(), '');
    assert.equal(await page.getByRole('status', { name: 'Relationship stage' }).textContent(), 'Strangers');
    await context.close();
    console.log(`PASS ${width}px configuration handoff, failure/retry, cancellation, switching, keyboard and layout`);
  }
  assert.deepEqual(errors, []);
  console.log(`Screenshots: ${artifacts}`);
} finally { await browser.close(); }
